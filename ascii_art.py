def generate_ascii_art(text, style='block'):
    """
    Generate ASCII art from text

    Args:
        text: String to convert to ASCII art
        style: Font style - 'block', 'slant', or 'mini'

    Returns:
        ASCII art string
    """
    text = text.upper()

    # Select font
    if style == 'slant':
        font = SLANT_FONT
    elif style == 'mini':
        font = MINI_FONT
    else:
        font = BLOCK_FONT

    # Handle unsupported characters
    supported_text = ''
    for char in text:
        if char in font:
            supported_text += char
        elif char.isspace():
            supported_text += ' '
        else:
            # Replace unsupported chars with ?
            supported_text += '?'

    if not supported_text.strip():
        return "No supported characters to render"

    # Get height of font
    height = len(font.get('A', ['']))

    # Build each line
    lines = []
    for row in range(height):
        line = ''
        for char in supported_text:
            if char in font:
                char_lines = font[char]
                if row < len(char_lines):
                    line += char_lines[row] + ' '
                else:
                    line += ' ' * (len(char_lines[0]) + 1)
        lines.append(line.rstrip())

    return '\n'.join(lines)


def main():
    """CLI interface for ASCII art generator"""
    import sys

    print("=" * 60)
    print("ASCII ART GENERATOR")
    print("=" * 60)

    # Get text input
    if len(sys.argv) > 1:
        text = ' '.join(sys.argv[1:])
    else:
        text = input("\nEnter text to convert: ").strip()
        if not text:
            print("No text provided!")
            return

    # Show available styles
    print("\nAvailable styles:")
    print("  1. block  - Bold block letters")
    print("  2. slant  - Slanted/diagonal style")
    print("  3. mini   - Compact mini style")
    print("  4. all    - Show all styles")

    style_choice = input("\nChoose style (1-4, default=1): ").strip() or "1"

    style_map = {
        '1': 'block',
        '2': 'slant',
        '3': 'mini',
        '4': 'all',
        'block': 'block',
        'slant': 'slant',
        'mini': 'mini',
        'all': 'all'
    }

    style = style_map.get(style_choice, 'block')

    print("\n" + "=" * 60)

    if style == 'all':
        for s in ['block', 'slant', 'mini']:
            print(f"\n{s.upper()} STYLE:")
            print("-" * 60)
            print(generate_ascii_art(text, s))
            print()
    else:
        print(generate_ascii_art(text, style))

    print("=" * 60)


if __name__ == "__main__":
    main()
